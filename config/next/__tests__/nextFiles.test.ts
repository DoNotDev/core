import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { PathResolver } from '../../utils/PathResolver.js';
import {
  NEXT_PAGE_EXTENSIONS,
  migrateNextFiles,
  nextFileName,
} from '../nextFiles.js';

const MARKER = '// Generated by @donotdev/config - DO NOT EDIT\n';

/** Next's page-file test: `\.(?:ext1|ext2…)$` (createValidFileMatcher). */
const nextPageFile = new RegExp(
  `\\.(?:${NEXT_PAGE_EXTENSIONS.map((e) => e.replace('.', '\\.')).join('|')})$`
);
/** Next's App Router page/route leaf test: `[\\/]page\.(?:exts)$`. */
const nextAppLeaf = new RegExp(
  `(^|[\\\\/])(page|route)\\.(?:${NEXT_PAGE_EXTENSIONS.map((e) => e.replace('.', '\\.')).join('|')})$`
);

describe('Next file marker', () => {
  it('no page source under src/pages is a Next page file', () => {
    for (const source of [
      'products/ProductPage.tsx',
      'HomePage.tsx',
      'legal/CgvPage.tsx',
      'index.tsx',
      '_app.tsx',
      'api/ping.ts',
    ]) {
      expect(nextPageFile.test(source)).toBe(false);
    }
  });

  it('generated App Router files are Next page/route files', () => {
    expect(nextAppLeaf.test(`produits/[slug]/${nextFileName('page', 'tsx')}`)).toBe(true);
    expect(nextAppLeaf.test(`sitemap.xml/${nextFileName('route', 'ts')}`)).toBe(true);
    expect(nextAppLeaf.test(`llms.txt/${nextFileName('route', 'ts')}`)).toBe(true);
    expect(nextAppLeaf.test('produits/[slug]/page.tsx')).toBe(false);
  });
});

describe('migrateNextFiles', () => {
  let appRoot: string;
  const logger = { warn: vi.fn(), debug: vi.fn() };
  const put = (rel: string, content: string) => {
    const file = join(appRoot, rel);
    mkdirSync(join(file, '..'), { recursive: true });
    writeFileSync(file, content);
    return file;
  };
  const at = (rel: string) => join(appRoot, rel);

  beforeEach(() => {
    appRoot = mkdtempSync(join(tmpdir(), 'dndev-nextfiles-'));
    PathResolver._reset();
    PathResolver.getInstance().setAppRoot(appRoot);
    logger.warn.mockClear();
  });

  afterEach(() => {
    rmSync(appRoot, { recursive: true, force: true });
    PathResolver._reset();
  });

  const run = (isCI = false) =>
    migrateNextFiles({ pathResolver: PathResolver.getInstance(), logger, isCI });

  it('renames the app files, removes stale generated files, leaves page sources alone', () => {
    put('src/app/layout.tsx', 'export default function L() {}\n');
    put('src/app/not-found.tsx', "export const dynamic = 'force-dynamic';\n");
    put('src/app/api/ping/route.ts', 'export async function GET() {}\n');
    put('src/proxy.ts', 'export function proxy() {}\n');
    put('src/app/produits/[slug]/page.tsx', `${MARKER}export default function P() {}\n`);
    put('src/app/sitemap.ts', `${MARKER}export default function sitemap() {}\n`);
    put('src/app/ClientLayout.tsx', "'use client';\n");
    put('src/pages/products/ProductPage.tsx', 'export default function P() {}\n');

    const { renamed, removed } = run();

    expect(renamed.sort()).toEqual(
      ['src/app/api/ping/route.ts', 'src/app/layout.tsx', 'src/app/not-found.tsx', 'src/proxy.ts'].sort()
    );
    expect(removed.sort()).toEqual(['src/app/produits/[slug]/page.tsx', 'src/app/sitemap.ts'].sort());
    expect(readFileSync(at('src/app/not-found.next.tsx'), 'utf8')).toContain('force-dynamic');
    expect(existsSync(at('src/app/layout.next.tsx'))).toBe(true);
    expect(existsSync(at('src/app/api/ping/route.next.ts'))).toBe(true);
    expect(existsSync(at('src/proxy.next.ts'))).toBe(true);
    expect(existsSync(at('src/app/ClientLayout.tsx'))).toBe(true);
    expect(existsSync(at('src/pages/products/ProductPage.tsx'))).toBe(true);
    expect(logger.warn).toHaveBeenCalledOnce();

    // Idempotent
    expect(run()).toEqual({ renamed: [], removed: [] });
  });

  it('fails in CI instead of renaming (a CI rename never reaches git)', () => {
    put('src/app/layout.tsx', 'export default function L() {}\n');
    expect(() => run(true)).toThrow(/layout\.tsx → layout\.next\.tsx/);
    expect(existsSync(at('src/app/layout.tsx'))).toBe(true);
  });

  it('still removes stale generated files in CI', () => {
    put('src/app/page.tsx', `${MARKER}export default function P() {}\n`);
    expect(run(true).removed).toEqual(['src/app/page.tsx']);
  });

  it('fails on a code metadata file, marked or not', () => {
    put('src/app/robots.ts', 'export default function robots() {}\n');
    expect(() => run()).toThrow(/robots\.ts/);
    rmSync(at('src/app/robots.ts'));
    put('src/app/icon.next.tsx', 'export default function Icon() {}\n');
    expect(() => run()).toThrow(/icon\.next\.tsx/);
  });

  it('refuses to overwrite an existing marked file', () => {
    put('src/app/layout.tsx', 'export default function A() {}\n');
    put('src/app/layout.next.tsx', 'export default function B() {}\n');
    expect(() => run()).toThrow(/Both src\/app\/layout\.tsx and src\/app\/layout\.next\.tsx exist/);
  });
});
