/**
 * @fileoverview Next file marker
 * @description Page sources live in `src/pages/**` (shared with Vite). Next also reads
 * `src/pages` as its Pages Router and has no option to turn it off. So the framework
 * gives Next a `pageExtensions` only Next files carry: `page.next.tsx`, `layout.next.tsx`,
 * `route.next.ts`, `proxy.next.ts`… A page source (`ProductPage.tsx`) never matches, so
 * no file under `src/pages` is ever a route, a bundle or a second React. Vite does not
 * read `pageExtensions`.
 *
 * Code metadata files (`sitemap.ts`, `robots.ts`, `icon.tsx`…) are not used: Turbopack
 * ignores them under a custom `pageExtensions` (verified on Next 16.4.5). The framework
 * serves them as route handlers (`sitemap.xml/route.next.ts`); static metadata files
 * (`favicon.ico`, `icon.png`, `opengraph-image.png`) are unaffected.
 *
 * Apps written before the marker are migrated: generated files are removed (the build
 * regenerates them), the app's own files are renamed in development and reported as an
 * error in CI, where a rename would never reach the repository.
 *
 * @version 0.1.0
 * @since 0.2.3
 * @author AMBROISE PARK Consulting
 */

import { renameSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';

/** Infix every Next route/special file carries. */
export const NEXT_FILE_MARKER = 'next';

/** Code extensions Next resolves. */
const CODE_EXTENSIONS = ['tsx', 'ts', 'jsx', 'js'];

/** Next `pageExtensions`: `page.next.tsx` is a page, `ProductPage.tsx` is not. */
export const NEXT_PAGE_EXTENSIONS = CODE_EXTENSIONS.map(
  (extension) => `${NEXT_FILE_MARKER}.${extension}`
);

/**
 * Name of a Next file with the marker.
 * @param {string} name - Base name (`page`, `layout`, `route`, `proxy`)
 * @param {'tsx'|'ts'|'jsx'|'js'} extension
 * @returns {string} e.g. `page.next.tsx`
 */
export function nextFileName(name, extension) {
  return `${name}.${NEXT_FILE_MARKER}.${extension}`;
}

/** Routing file conventions Next reads under app/. */
const APP_FILE_NAMES = [
  'page',
  'route',
  'layout',
  'template',
  'default',
  'loading',
  'error',
  'global-error',
  'not-found',
  'global-not-found',
  'forbidden',
  'unauthorized',
];

/** Code metadata conventions under app/ (not supported with the marker). */
const METADATA_FILE_NAMES = [
  'sitemap',
  'robots',
  'manifest',
  'icon',
  'apple-icon',
  'opengraph-image',
  'twitter-image',
];

/** File conventions Next reads next to app/ (src/ or the app root). */
const ROOT_FILE_NAMES = ['proxy', 'middleware', 'instrumentation'];

/** Header of every file the framework generates. */
const GENERATION_MARKER = '// Generated by @donotdev/config';

/**
 * Parse `<name>[.next].<ext>` for one of the given names.
 * @returns {{ name: string, extension: string, marked: boolean } | null}
 */
function matchConvention(fileName, names) {
  const match = fileName.match(
    new RegExp(`^(.+?)(\\.${NEXT_FILE_MARKER})?\\.(tsx|ts|jsx|js)$`)
  );
  if (!match) return null;
  const [, name, marked, extension] = match;
  return names.includes(name) ? { name, extension, marked: !!marked } : null;
}

/**
 * Next convention files of the app.
 * @returns {Array<{ file: string, name: string, extension: string, marked: boolean, metadata: boolean }>}
 */
function findConventionFiles(pathResolver) {
  const found = [];
  const appDir = pathResolver.resolveAppPath('src/app');

  const walk = (dir) => {
    for (const entry of pathResolver.readdirSync(dir, { withFileTypes: true })) {
      const file = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(file);
        continue;
      }
      if (!entry.isFile()) continue;
      const routing = matchConvention(entry.name, APP_FILE_NAMES);
      if (routing) found.push({ file, ...routing, metadata: false });
      const metadata = matchConvention(entry.name, METADATA_FILE_NAMES);
      if (metadata) found.push({ file, ...metadata, metadata: true });
    }
  };
  if (pathResolver.pathExists(appDir)) walk(appDir);

  for (const dir of [
    pathResolver.resolveAppPath('src'),
    pathResolver.getAppRoot(),
  ]) {
    if (!pathResolver.pathExists(dir)) continue;
    for (const entry of pathResolver.readdirSync(dir, { withFileTypes: true })) {
      const root = entry.isFile() && matchConvention(entry.name, ROOT_FILE_NAMES);
      if (root) found.push({ file: join(dir, entry.name), ...root, metadata: false });
    }
  }
  return found;
}

/**
 * Bring an app's Next files to the marker before Next scans them.
 *
 * - generated file without the marker (earlier framework version): removed, the build
 *   regenerates it with the marker
 * - the app's own file without the marker: renamed (`layout.tsx` → `layout.next.tsx`)
 *   in development; in CI the build fails with the list (a CI rename never reaches git)
 * - code metadata file (`sitemap.ts`, `icon.tsx`…): the build fails, Turbopack ignores
 *   them with the marker
 *
 * Idempotent: an app already migrated has nothing to do.
 *
 * @param {Object} options
 * @param {import('../utils/PathResolver.js').PathResolver} options.pathResolver
 * @param {Object} options.logger
 * @param {boolean} options.isCI - CI build: report, never rename
 * @returns {{ renamed: string[], removed: string[] }} App-relative paths
 * @throws {Error} On a code metadata file, an unmarked file in CI, or a rename target that exists
 */
export function migrateNextFiles({ pathResolver, logger, isCI }) {
  const appRoot = pathResolver.getAppRoot();
  const rel = (file) => relative(appRoot, file);
  const renamed = [];
  const removed = [];
  const toRename = [];
  const metadataFiles = [];

  for (const found of findConventionFiles(pathResolver)) {
    const content = pathResolver.readSync(found.file, { format: 'text' }) || '';
    if (!found.marked && content.startsWith(GENERATION_MARKER)) {
      pathResolver.removeSync(found.file);
      removed.push(rel(found.file));
      continue;
    }
    if (found.metadata) metadataFiles.push(rel(found.file));
    else if (!found.marked) toRename.push(found);
  }

  if (metadataFiles.length > 0) {
    throw new Error(
      `[dndev] Next ignores code metadata files with the framework's file marker: ${metadataFiles.join(', ')}. ` +
        `Serve each as a route handler (e.g. src/app/robots.txt/${nextFileName('route', 'ts')}) or a static file ` +
        '(icon.png, opengraph-image.png). The sitemap and llms.txt are generated by the framework.'
    );
  }

  if (isCI && toRename.length > 0) {
    throw new Error(
      `[dndev] Next files must carry the .${NEXT_FILE_MARKER}. marker (src/pages is never a Next route). Rename: ` +
        toRename
          .map(
            ({ file, name, extension }) =>
              `${rel(file)} → ${nextFileName(name, extension)}`
          )
          .join(', ') +
        '. Running the app once in development renames them.'
    );
  }

  for (const { file, name, extension } of toRename) {
    const target = join(dirname(file), nextFileName(name, extension));
    if (pathResolver.pathExists(target)) {
      throw new Error(
        `[dndev] Both ${rel(file)} and ${rel(target)} exist. Next only reads ` +
          `*.${NEXT_FILE_MARKER}.* files: merge ${basename(file)} into ${basename(target)} and delete it.`
      );
    }
    renameSync(file, target);
    renamed.push(rel(file));
  }

  if (renamed.length > 0) {
    logger.warn(
      `Next files renamed to *.${NEXT_FILE_MARKER}.* (src/pages is never a Next route): ` +
        `${renamed.join(', ')}. Commit the renames.`
    );
  }
  if (removed.length > 0) {
    logger.debug(
      `Removed generated Next files without marker: ${removed.join(', ')}`
    );
  }
  return { renamed, removed };
}
