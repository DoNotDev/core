/**
 * @fileoverview Next route handler: Revalidation webhook route
 * @description `src/app/api/dndev/revalidate/route.next.ts`: the Supabase database webhook that invalidates the cached pages a changed record appears on. Methods of {@link NextRouteHandler} (mixed into its prototype by
 * `../RouteHandler.js`); `this` is the route handler.
 *
 * @version 0.0.1
 * @since 0.3.2
 * @author AMBROISE PARK Consulting
 */

import { GENERATED_PATHS } from '../../../constants.js';
import { routeParams } from '../../../utils/publicPages.js';
import { REVALIDATE_SECRET_ENV } from '../../revalidation.js';

export const revalidationRouteMethods = {
  /**
   * Route of the revalidation webhook's map ({@link generateRevalidationContent}): a cached
   * page (site tree, no catch-all) as `{ path }` when static, `{ path, collection }` when
   * its single `:param` is filled by its entity's records (`meta.entity`: the collection of
   * the entity its page declares in PageMeta; the sitemap's
   * route → collection reading, noindex pages included: they are cached too).
   *
   * @param {Object} route - Route object (`path` in React Router syntax)
   * @returns {{ path: string, collection?: string } | null} null when not revalidated per record
   * @since 0.3.2
   */
  revalidationRoute(route) {
    if (this.isSessionOnlyRoute(route) || route.path.includes('*')) return null;
    const params = routeParams(route.path);
    if (params.length === 0) return { path: route.path };
    const collection = route.meta?.entity;
    return params.length === 1 && collection ? { path: route.path, collection } : null;
  },

  /**
   * Source of the revalidation route handler (`src/app/api/dndev/revalidate/route.next.ts`,
   * POST): a Supabase database webhook calls it on insert / update / delete, authenticated
   * by `Authorization: Bearer $DNDEV_REVALIDATE_SECRET`; it invalidates the cached pages
   * the changed record appears on (handleRevalidationWebhook in @donotdev/core/next).
   *
   * @param {Object} routeData - Discovered routes
   * @returns {string}
   * @since 0.3.2
   */
  generateRevalidationContent(routeData) {
    const routes = routeData.routes
      .map((route) => this.revalidationRoute(route))
      .filter(Boolean);
    const routing = {
      languages: this.options.languages,
      defaultLanguage: this.options.defaultLanguage,
    };
    return `// Generated by @donotdev/config - DO NOT EDIT
// Regenerated on every build from src/pages (PageMeta).
// On-demand revalidation: a Supabase database webhook POSTs each row change here
// (Authorization: Bearer $${REVALIDATE_SECRET_ENV}). The cached pages showing the row (its entity
// pages in every language, the static pages, sitemap.xml, llms.txt) are invalidated and
// re-rendered on their next visit. Secret unset or under 32 characters: every call fails
// (500), loudly. Watch public content tables only: each call invalidates every static page.

import { revalidatePath } from 'next/cache';

import type { LanguageRouting } from '@donotdev/core/server';
import { handleRevalidationWebhook } from '@donotdev/core/next';
import type { PublicRoute } from '@donotdev/core/next';
import { readDatabaseWebhook } from '@donotdev/supabase/server';

const LANGUAGE_ROUTING: LanguageRouting = ${JSON.stringify(routing)};

/** Cached pages: static ones, entity ones with the table that fills their param */
const ROUTES: PublicRoute[] = ${JSON.stringify(routes, null, 2)};

export async function POST(request: Request): Promise<Response> {
  return handleRevalidationWebhook(request, {
    secret: process.env.${REVALIDATE_SECRET_ENV},
    routes: ROUTES,
    routing: LANGUAGE_ROUTING,
    readChange: readDatabaseWebhook,
    revalidatePath,
  });
}
`;
  },

  /**
   * Write the revalidation route handler (`/api/dndev/revalidate`,
   * {@link generateRevalidationContent}) for an app on @donotdev/supabase (the webhook
   * format it reads). Outside the language tree and under `api`, so the proxy never runs
   * for it. Removed with the other discovery artifacts when no longer generated.
   *
   * @param {Object} routeData - Discovered routes
   * @since 0.3.2
   */
  generateRevalidationRoute(routeData) {
    if (this.options.routingMode !== 'app') return;
    if (!this.appDependsOn('@donotdev/supabase')) return;
    this.writeGeneratedFile(
      GENERATED_PATHS.next.revalidateRoute,
      this.generateRevalidationContent(routeData),
      'revalidation route'
    );
  },
};
